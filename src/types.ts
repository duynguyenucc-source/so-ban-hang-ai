export type PartyType = 'seller' | 'buyer';

export interface Seller {
  id: string;
  name: string;
  phone: string;
  type: 'nha_vuon' | 'thuong_lai' | 'dai_ly'; // Garden, Trader, Dealer
  address: string;
  totalSuppliedWeight: number; // kg
  currentDebt: number; // Positive: We owe them (Payable). Negative: They owe us (Advance).
}

export interface Buyer {
  id: string;
  name: string;
  phone: string;
  companyName: string;
  address: string;
  totalPurchasedWeight: number; // kg
  currentDebt: number; // Positive: They owe us (Receivable). Negative: We owe them.
}

export type LotStatus = 'moi_nhap' | 'dang_phoi' | 'da_phan_loai' | 'dang_che_bien' | 'da_hoan_thanh';

export interface Lot {
  id: string;
  code: string; // e.g., LÔ-DUA-20260701-001
  sourceSellerId: string;
  sellerName: string;
  importDate: string;
  initialWeight: number; // kg
  currentWeight: number; // kg
  unitPrice: number; // VND/kg
  totalCost: number; // VND
  status: LotStatus;
  qualityGrade: 'loai_1' | 'loai_2' | 'loai_3' | 'hon_hop';
  qualityNotes: string[]; // ['nứt', 'non', 'đạt chuẩn', 'ẩm cao']
  location: string; // Khu vực A, Kho Bãi 1, etc.
  processedWeight: number; // kg that has been converted
  note?: string;
}

export interface PurchaseTicket {
  id: string;
  lotId: string; // The lot generated by this purchase
  sellerId: string;
  sellerName: string;
  date: string;
  licensePlate: string;
  grossWeight: number; // Cân tổng (kg)
  tareWeight: number; // Cân bì (kg)
  netWeight: number; // Cân thực nhận (kg)
  unitPrice: number; // Đơn giá VND/kg
  subtotal: number; // Thành tiền gốc = netWeight * unitPrice
  deductions: {
    moistureDeductionKg: number; // Trừ tạp ẩm (kg)
    qualityDeductionKg: number; // Trừ nứt nẻ/mọc mầm (kg)
    otherDeductionVnd: number; // Trừ chi phí phụ (VND)
  };
  finalWeight: number; // Khối lượng tính tiền = netWeight - deductions
  finalAmount: number; // Thành tiền thực tế = (finalWeight * unitPrice) - otherDeductionVnd
  paidAmount: number; // Đã thanh toán (VND)
  paymentStatus: 'da_thanh_toan' | 'ghi_no' | 'thanh_toan_mot_phan';
  note?: string;
  scannedImage?: string; // Simulated base64 or placeholder
}

export interface ProcessingRecord {
  id: string;
  lotId: string; // Source Lot ID
  lotCode: string;
  date: string;
  inputWeight: number; // Khối lượng dừa đưa vào tách vỏ (kg)
  outputMeat: number; // Cơm dừa thu hồi (kg)
  outputShell: number; // Gáo dừa thu hồi (kg)
  outputCoir: number; // Xơ dừa thu hồi (kg)
  outputWaste: number; // Dừa hư, loại thải (kg)
  lossWeight: number; // Hao hụt thực tế = input - (meat + shell + coir + waste)
  recoveryRate: number; // Tỉ lệ thu hồi cơm dừa % = (outputMeat / inputWeight) * 100
  lossRate: number; // Tỉ lệ hao hụt % = (lossWeight / inputWeight) * 100
  laborCost: number; // Chi phí bốc xếp, nhân công (VND)
  notes?: string;
}

export interface ShipmentItem {
  type: 'com_dua' | 'gao_dua' | 'xo_dua' | 'nguyen_trai';
  weight: number; // kg
  unitPrice: number; // VND/kg
  subtotal: number;
}

export type ShipmentStatus = 'dang_gom' | 'da_xuat' | 'da_giao';

export interface ContainerShipment {
  id: string;
  code: string; // e.g., CONT-MSKU-202607-001
  buyerId: string;
  buyerName: string;
  exportDate: string;
  licensePlate: string; // Xe container
  driverName: string;
  items: ShipmentItem[];
  lotIds: string[]; // Lots included in this container
  transportCost: number; // Chi phí vận chuyển (VND)
  loadingCost: number; // Chi phí bốc xếp (VND)
  otherCosts: number; // Chi phí hải quan, kiểm dịch, v.v. (VND)
  totalRevenue: number; // Tổng doanh thu từ các mặt hàng (VND)
  totalCostOfGoods: number; // Giá vốn hàng bán (tổng chi phí thu mua các lô tương ứng)
  estimatedProfit: number; // Lợi nhuận tạm tính = totalRevenue - totalCostOfGoods - chi_phi
  paidAmount: number; // Đã thanh toán (VND)
  paymentStatus: 'da_thanh_toan' | 'ghi_no' | 'thanh_toan_mot_phan';
  status: ShipmentStatus;
  note?: string;
}

export interface DebtTransaction {
  id: string;
  partyId: string; // sellerId or buyerId
  partyName: string;
  partyType: PartyType;
  date: string;
  type: 'thu_mua' | 'xuat_hang' | 'thanh_toan' | 'ung_truoc' | 'giam_tru';
  amount: number; // VND
  balanceAfter: number; // Dư nợ sau giao dịch (VND)
  note?: string;
}

